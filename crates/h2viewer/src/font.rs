/// White glyphs on transparent, one cell per character in a single row.
pub fn atlas() -> Image {
    let w = CELL_W * CHARS.len();
    let h = CELL_H;
    let mut rgba = vec![0u8; w * h * 4];
    for (g, rows) in GLYPHS.iter().enumerate() {
        for (y, row) in rows.iter().enumerate() {
            for x in 0..GLYPH_W {
                if row & (0x10 >> x) == 0 {
                    continue;
                }
                for dy in 0..SCALE {
                    for dx in 0..SCALE {
                        let px = g * CELL_W + SCALE / 2 + x * SCALE + dx;
                        let py = SCALE / 2 + y * SCALE + dy;
                        rgba[(py * w + px) * 4..][..4].copy_from_slice(&[255; 4]);
                    }
                }
            }
        }
    }
    Image {
        width: w as u32,
        height: h as u32,
        rgba,
    }
}

/// Texture rectangle (u0, v0, u1, v1) of a character's cell.
pub fn glyph_uv(c: char) -> Option<[f32; 4]> {
    let c = if c.is_ascii_lowercase() && c != 'x' {
        c.to_ascii_uppercase()
    } else {
        c
    };
    let i = CHARS.find(c)?;
    let n = CHARS.len() as f32;
    Some([i as f32 / n, 0.0, (i + 1) as f32 / n, 1.0])
}

/// Width / height of a character cell.
pub const ASPECT: f32 = CELL_W as f32 / CELL_H as f32;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_char_has_a_glyph() {
        assert_eq!(CHARS.chars().count(), GLYPHS.len());
        assert!(glyph_uv('7').is_some());
        assert!(glyph_uv('r').is_some());
        assert!(glyph_uv('#').is_none());
    }

    #[test]
    fn atlas_has_ink() {
        let img = atlas();
        assert!(img.rgba.chunks(4).any(|p| p[3] == 255));
    }
}
